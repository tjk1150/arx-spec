    @Test
    fun theVectorFileComparesAt1e9WithThePerEffectCap() {
        assertEquals(1e-9, vectors.getValue("tolerance").jsonPrimitive.double)
        assertEquals(EffectSimulation.MAX_PARTICLES, vectors.getValue("maxParticles").jsonPrimitive.int)
        val cases = vectors.getValue("cases").jsonArray.map { it.jsonObject }
        assertEquals(presets.keys.sorted(), cases.map { it.getValue("effect").jsonObject.getValue("preset").jsonPrimitive.content }.toSet().sorted())
        val counts = cases.flatMap { case -> case.getValue("expect").jsonArray.map { it.jsonObject.getValue("count").jsonPrimitive.int } }
        assertEquals(EffectSimulation.MAX_PARTICLES, counts.max())
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("cases")
    fun matchesTheReferenceVectors(name: String, case: JsonObject) {
        assertTrue((case.keys - caseKeys).isEmpty(), "$name: unchecked keys ${case.keys - caseKeys}")
        val tolerance = vectors.getValue("tolerance").jsonPrimitive.double
        val effectJson = case.getValue("effect").jsonObject
        val preset = presetOf(effectJson.getValue("preset").jsonPrimitive.content, case["presetOverrides"]?.jsonObject)
        val simulation = EffectSimulation(effectOf(effectJson, preset), preset)
        val frames = case.getValue("expect").jsonArray.map { it.jsonObject }
        assertEquals(case.getValue("times").jsonArray.map { it.jsonPrimitive.double }, frames.map { it.getValue("time").jsonPrimitive.double })
        for (frame in frames) {
            assertTrue((frame.keys - frameKeys).isEmpty(), "$name: unchecked frame keys ${frame.keys - frameKeys}")
            val time = frame.getValue("time").jsonPrimitive.double
            // A restart row: the target was found again, so the clock starts at 0 and runs to this time (spec 7.1).
            if (frame["restart"]?.jsonPrimitive?.boolean == true) simulation.restart()
            simulation.advance(time)
            val live = simulation.particles()
            assertEquals(frame.getValue("count").jsonPrimitive.int, live.size, "$name at $time: count")
            for (expected in frame.getValue("particles").jsonArray.map { it.jsonObject }) {
                val slot = expected.getValue("slot").jsonPrimitive.int
                val view = live[slot]
                assertEquals(expected.getValue("index").jsonPrimitive.long, view.index, "$name at $time slot $slot: index")
                val wanted = expected.numbers("position")!! + expected.getValue("size").jsonPrimitive.double +
                    expected.getValue("angleDegrees").jsonPrimitive.double + expected.numbers("color")!! +
                    expected.getValue("alpha").jsonPrimitive.double
                val actual = listOf(view.x, view.y, view.z, view.size, view.angleDegrees, view.red, view.green, view.blue, view.alpha)
                assertEquals(9, wanted.size)
                actual.zip(wanted).forEachIndexed { field, (mine, theirs) ->
                    assertTrue(abs(mine - theirs) <= tolerance, "$name at $time slot $slot field $field: $mine vs $theirs")
                }
            }
        }
    }

