    @Test
    fun keepsThe256CapAcrossARestartAndRefillsFromTheOldestBirths() {
        val crowded = presetOf("sparkle", null).copy(rate = 400.0, lifetime = Vec2(2.0, 2.0))
        val simulation = simulationOf(SPARKLE_JSON, crowded)
        simulation.advance(3.0)
        assertEquals(EffectSimulation.MAX_PARTICLES, simulation.particles().size)
        simulation.restart()
        val early = simulation.stateAt(0.5)
        assertEquals(floor(0.5 * 400).toInt() + 1, early.size)
        assertEquals(early.indices.map { it.toLong() }, early.map { it.index })
        assertEquals(EffectSimulation.MAX_PARTICLES, simulation.stateAt(1.0).size)
    }

    @Test
    fun theConstantCurveKeepsEveryLiveParticleAtFullAlpha() {
        val constant = presetOf("sparkle", null).copy(alphaCurve = "constant")
        val simulation = simulationOf(SPARKLE_JSON, constant)
