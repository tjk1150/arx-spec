    @Test
    fun restartEmptiesTheLiveParticlesAsBeforeTheFirstAdvance() {
        val simulation = simulationOf(SPARKLE_JSON)
        simulation.advance(4.6)
        assertTrue(simulation.particles().isNotEmpty())
        simulation.restart()
        assertEquals(0, simulation.particles().size)
