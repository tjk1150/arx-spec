/**
 * EffectSimulation against fixtures/effects/simulation.json (the vectors the TypeScript
 * simulation also passes, generated by tools/effects_reference.py) plus the curve, cadence and
 * cap rules of spec/extensions/ARX_effects.md sections 6 and 7.
 */
class EffectSimulationTest {
    companion object {
        private val caseKeys = setOf("name", "effect", "presetOverrides", "times", "expect")
        private val frameKeys = setOf("time", "restart", "count", "particles")

        val vectors: JsonObject by lazy {
            Json.parseToJsonElement(Fixtures.file("effects/simulation.json").readText()).jsonObject
        }

        private val presets: ArxEffectPresetTable by lazy { checkNotNull(EffectPresets.bundled) }

        @JvmStatic
        fun cases(): List<Arguments> = vectors.getValue("cases").jsonArray.map { element ->
            val case = element.jsonObject
            Arguments.of(case.getValue("name").jsonPrimitive.content, case)
        }

        private fun JsonObject.numbers(key: String): List<Double>? =
            this[key]?.jsonArray?.map { it.jsonPrimitive.double }

        /** The resolved effect of a manifest effect: defaults filled as the validator fills them. */
        fun effectOf(json: JsonObject, preset: ArxEffectPreset): ArxEffect {
            val transform = json["transform"]?.jsonObject
            return ArxEffect(
                id = json.getValue("id").jsonPrimitive.content,
                preset = json.getValue("preset").jsonPrimitive.content,
                colors = json.getValue("colors").jsonArray.map { it.jsonPrimitive.content },
                amount = json["amount"]?.jsonPrimitive?.double ?: EffectConstants.DEFAULT_AMOUNT,
                size = json["size"]?.jsonPrimitive?.double ?: preset.size,
                speed = json["speed"]?.jsonPrimitive?.double ?: EffectConstants.DEFAULT_SPEED,
                sprite = json["sprite"]?.jsonPrimitive?.content ?: preset.sprite,
                transform = ArxTransform.from(
                    transform?.let { ArxManifest.TransformInput(it.numbers("position"), it.numbers("rotation"), it.numbers("scale")) },
                ),
            )
        }

        /** The named bundled preset with the fixture's overrides; an override this test cannot apply fails. */
        fun presetOf(name: String, overrides: JsonObject?): ArxEffectPreset =
            (overrides ?: JsonObject(emptyMap())).entries.fold(presets.getValue(name)) { preset, (key, value) ->
                when (key) {
                    "rate" -> preset.copy(rate = value.jsonPrimitive.double)
                    "lifetime" -> value.jsonArray.map { it.jsonPrimitive.double }.let { preset.copy(lifetime = Vec2(it[0], it[1])) }
                    "alphaCurve" -> preset.copy(alphaCurve = value.jsonPrimitive.content)
                    else -> error("presetOverrides.$key is not handled by this test")
                }
            }

        private val SPARKLE_JSON = Json.parseToJsonElement(
            """{"id": "sparkle-1", "preset": "sparkle", "colors": ["#FF0071", "#18004A"]}""",
        ).jsonObject
        private val BURST_JSON = Json.parseToJsonElement(
            """{"id": "burst-a", "preset": "burst", "colors": ["#FFD700", "#FF4500"],
                "transform": {"rotation": [0.2, -0.1, 0.3, 0.9]}, "amount": 0.7}""",
        ).jsonObject

        fun simulationOf(json: JsonObject, preset: ArxEffectPreset = presetOf(json.getValue("preset").jsonPrimitive.content, null)) =
            EffectSimulation(effectOf(json, preset), preset)
    }

    /** A plain copy of a view, so a later advance cannot change what a test compares. */
    private data class Snapshot(
        val index: Long, val x: Double, val y: Double, val z: Double, val size: Double, val angleDegrees: Double,
        val red: Double, val green: Double, val blue: Double, val alpha: Double,
    )

    private fun ParticleView.snapshot() = Snapshot(index, x, y, z, size, angleDegrees, red, green, blue, alpha)

    private fun EffectSimulation.stateAt(time: Double): List<Snapshot> {
        advance(time)
        return particles().map { it.snapshot() }
    }

    // Seed and random sequence (spec 7.2)

    @Test
    fun hashesTheSpecCheckStringsToTheSpecSeeds() {
        assertEquals(0x811C9DC5L.toInt(), EffectRandom.fnv1a32(""))
        assertEquals(0xE40C292CL.toInt(), EffectRandom.fnv1a32("a"))
        assertEquals(0xDF005EFBL.toInt(), EffectRandom.fnv1a32("sparkle-1"))
        for ((text, seed) in vectors.getValue("checks").jsonObject.getValue("seeds").jsonObject) {
            assertEquals(seed.jsonPrimitive.long.toInt(), EffectRandom.fnv1a32(text), "seed of \"$text\"")
        }
    }

    @Test
    fun hashesUtf8BytesAsTextEncoderDoes() {
        // Values from tools/effects_reference.py: e-acute is bytes C3 A9, the emoji a surrogate pair in UTF-16.
        assertEquals(0x1E9DE8C1, EffectRandom.fnv1a32("é"))
        assertEquals(0x33A29608, EffectRandom.fnv1a32("😀"))
        // A lone surrogate encodes as U+FFFD (EF BF BD) like the browser TextEncoder, not as '?' like String.toByteArray.
        assertEquals(0x03479C4A, EffectRandom.fnv1a32("\uD800"))
        assertEquals(EffectRandom.fnv1a32("�"), EffectRandom.fnv1a32("\uD800"))
    }

    @Test
    fun startsTheSpecSeedWithTheSpecValues() {
        val sequence = vectors.getValue("checks").jsonObject.getValue("sequence").jsonObject
        val seed = sequence.getValue("seed").jsonPrimitive.long.toInt()
        val values = sequence.getValue("values").jsonArray.map { it.jsonPrimitive.double }
        assertEquals(listOf(0.7602949764113873, 0.79540013987571, 0.5259187174960971), values)
        assertEquals(values, (0L until 3L).map { EffectRandom.mulberry32At(seed, it) })
    }

    /** The spec's step-by-step generator with unsigned 32-bit values held in Longs: an independent check of Int overflow. */
    private fun specSequence(seed: Long, count: Int): List<Double> {
        val mask = 0xFFFFFFFFL
        fun imul(left: Long, right: Long) = (left * right) and mask
        var state = seed and mask
        return List(count) {
            state = (state + 0x6D2B79F5L) and mask
            var value = imul(state xor (state ushr 15), state or 1L)
            value = ((value + imul(value xor (value ushr 7), value or 61L)) and mask) xor value
            (value xor (value ushr 14)).toDouble() / 4294967296.0
        }
    }

    @Test
    fun readsEachPositionAsTheStepByStepSequenceDoes() {
        for (seed in listOf(0L, 1L, 0x7FFFFFFFL, 0x80000000L, 0xFFFFFFFFL, 0xDF005EFBL)) {
            val expected = specSequence(seed, 200)
            val actual = (0L until 200L).map { EffectRandom.mulberry32At(seed.toInt(), it) }
            assertEquals(expected, actual, "seed ${seed.toString(16)}")
        }
    }

    @Test
    fun overflowsLikeMathImulOnBoundarySeedsAndPositions() {
        // Values printed by packages/arx-core/src/effects/utils/random.ts (mulberry32At) under Node.
        val positions = listOf(0L, 1L, (1L shl 31) - 1, 1L shl 31, (1L shl 32) - 1, (1L shl 32) + 5, (1L shl 40) + 3)
        val expected = mapOf(
            0L to listOf(0.26642920868471265, 0.0003297457005828619, 0.7470325820613652, 0.8205775609239936, 0.0, 0.5450490827206522, 0.1462021479383111),
            1L to listOf(0.6270739405881613, 0.002735721180215478, 0.008765385951846838, 0.3190071755088866, 1.4668330550193787e-8, 0.281103502959013, 0.9810509674716741),
            0x7FFFFFFFL to listOf(0.4290980885270983, 0.12713524978607893, 0.033185361651703715, 0.8964226141106337, 0.7470325820613652, 0.9531875969842076, 0.39639189024455845),
            0x80000000L to listOf(0.8205775609239936, 0.4481089550536126, 0.0, 0.26642920868471265, 0.7470325820613652, 0.4205148529727012, 0.5120457962621003),
            0xFFFFFFFFL to listOf(0.8964226141106337, 0.189478256739676, 0.7470325820613652, 0.4290980885270983, 0.033185361651703715, 0.5391399988438934, 0.9440599093213677),
            0x92D48609L to listOf(0.9687821881379932, 0.1577923847362399, 0.9558129352517426, 0.9922336346935481, 0.7506296904757619, 0.4295327684376389, 0.7769853791687638),
        )
        for ((seed, values) in expected) {
            assertEquals(values, positions.map { EffectRandom.mulberry32At(seed.toInt(), it) }, "seed ${seed.toString(16)}")
        }
        // Position p and p + 2^32 share a state, as Math.imul reduces position + 1 mod 2^32.
        assertEquals(EffectRandom.mulberry32At(7, 5), EffectRandom.mulberry32At(7, (1L shl 32) + 5))
        assertTrue((0L until 1000L).all { EffectRandom.mulberry32At(-1, it).let { value -> value >= 0.0 && value < 1.0 } })
    }

    // Alpha curves (spec 6)

    @Test
    fun evaluatesTheFiveAlphaCurves() {
        val samples = mapOf(
            "linearFadeOut" to listOf(0.0 to 1.0, 0.25 to 0.75, 0.5 to 0.5, 1.0 to 0.0),
            "easeFadeOut" to listOf(0.0 to 1.0, 0.5 to 0.75, 0.9 to 0.19, 1.0 to 0.0),
            "quickFadeInOut" to listOf(0.0 to 0.0, 0.05 to 0.5, 0.1 to 1.0, 0.5 to 1.0, 0.95 to 0.5, 1.0 to 0.0),
            "gradualFadeInOut" to listOf(0.0 to 0.0, 0.15 to 0.5, 0.3 to 1.0, 0.5 to 1.0, 0.85 to 0.5, 1.0 to 0.0),
            "constant" to listOf(0.0 to 1.0, 0.5 to 1.0, 0.999 to 1.0, 1.0 to 1.0),
        )
        assertEquals(AlphaCurves.NAMES, samples.keys)
        for ((name, points) in samples) {
            for ((life, alpha) in points) {
                assertTrue(abs(AlphaCurves.alpha(name, life) - alpha) <= 1e-12, "$name at $life: ${AlphaCurves.alpha(name, life)}")
            }
        }
        assertFailsWith<IllegalArgumentException> { AlphaCurves.alpha("sudden", 0.5) }
    }

