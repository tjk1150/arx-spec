    @Test
    fun aRestartedSimulationReplaysAFreshOneFromTime0() {
        for (json in listOf(SPARKLE_JSON, BURST_JSON)) {
            val restarted = simulationOf(json)
            for (frame in 1..280) restarted.advance(frame / 60.0)
            restarted.restart()
            for (time in listOf(0.0, 0.05, 0.5, 1.25, 1.55, 3.05)) {
                assertEquals(simulationOf(json).stateAt(time), restarted.stateAt(time), "${json["id"]} at $time")
            }
        }
    }

    @Test
    fun aRestartStartsAgainAtBirth0() {
        val simulation = simulationOf(SPARKLE_JSON)
        assertTrue(simulation.stateAt(4.6).first().index > 0)
        simulation.restart()
        assertEquals(listOf(0L), simulation.stateAt(0.0).map { it.index })
