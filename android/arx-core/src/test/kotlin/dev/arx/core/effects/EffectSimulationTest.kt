    // Limits and edges

    @Test
    fun keepsAtMost256LiveParticlesTheOldestOnes() {
        val crowded = presetOf("sparkle", null).copy(rate = 400.0, lifetime = Vec2(2.0, 2.0))
        val simulation = simulationOf(SPARKLE_JSON, crowded)
        for (time in listOf(0.5, 0.7, 1.0, 1.9, 4.0)) {
            simulation.advance(time)
            val live = simulation.particles()
            assertEquals(min(EffectSimulation.MAX_PARTICLES, floor(time * 400).toInt() + 1), live.size, "at $time")
            val indexes = live.map { it.index }
            assertEquals(indexes.sorted(), indexes)
        }
    }

    @Test
    fun givesTheSameParticlesAfterJumpingBackAndForthInTime() {
        // Every particle is a function of its birth number and the time, so what earlier frames computed
        // can never leak into a later one, whichever times came before.
        val wide = presetOf("sparkle", null).copy(rate = 150.0, lifetime = Vec2(0.05, 9.0))
        for ((json, preset) in listOf(SPARKLE_JSON to presetOf("sparkle", null), BURST_JSON to presetOf("burst", null), SPARKLE_JSON to wide)) {
            val jumping = simulationOf(json, preset)
            for (time in listOf(30.0, 2.0, 30.0, 0.5, 12.25, 12.25, 3.0, 45.5, 1.0)) {
                assertEquals(simulationOf(json, preset).stateAt(time), jumping.stateAt(time), "${json["id"]} rate ${preset.rate} at $time")
            }
        }
    }

    @Test
    fun copiesTheLiveStateInBirthOrderAsTheViewsReadIt() {
        val simulation = simulationOf(BURST_JSON)
        val state = DoubleArray(EffectSimulation.MAX_PARTICLES * EffectSimulation.STATE_STRIDE) { Double.NaN }
        for (time in listOf(0.0, 0.3, 1.55, 3.05)) {
            simulation.advance(time)
            val live = simulation.particles()
            assertTrue(live.isNotEmpty(), "at $time")
            assertEquals(live.size, simulation.copyState(state), "count at $time")
            live.forEachIndexed { slot, view ->
                val base = slot * EffectSimulation.STATE_STRIDE
                assertEquals(
                    listOf(view.x, view.y, view.z, view.size, view.angleDegrees, view.red, view.green, view.blue, view.alpha),
                    (base until base + EffectSimulation.STATE_STRIDE).map { state[it] },
                    "slot $slot at $time",
                )
            }
        }
        simulation.restart()
        assertEquals(0, simulation.copyState(state))
        assertFailsWith<IllegalArgumentException> {
            simulation.advance(3.05)
            simulation.copyState(DoubleArray(0))
        }
    }

