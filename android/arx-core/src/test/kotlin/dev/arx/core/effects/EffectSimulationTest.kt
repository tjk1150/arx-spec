        assertFailsWith<IllegalArgumentException> { simulationOf(SPARKLE_JSON, sparkle.copy(rate = 0.0)) }
        assertFailsWith<IllegalArgumentException> {
            simulationOf(SPARKLE_JSON, sparkle.copy(emission = ArxEffectEmission.Burst(emitSeconds = 0.0, pauseSeconds = 0.0)))
        }
        assertFailsWith<IllegalArgumentException> { simulationOf(SPARKLE_JSON, sparkle.copy(alphaCurve = "sudden")) }
    }
